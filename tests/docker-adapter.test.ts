function dockerFixture(options: {
  startError?: Error;
  securityOptions?: string[];
  managedInstanceId?: string;
  managedChallengeId?: string;
  existingNetwork?: boolean;
  existingContainer?: boolean;
  oomKilled?: boolean;
  ingressAttached?: boolean;
  ingressRunning?: boolean;
  availableImages?: string[];
  serverVersion?: string;
  networkOptions?: Record<string, string>;
  networkDriver?: string;
  enableIPv6?: boolean;
  extraNetwork?: boolean;
  entryServices?: string;
  runtimes?: Record<string, unknown>;
} = {}) {
  const containerRemove = vi.fn(async () => undefined);
  const networkRemove = vi.fn(async () => undefined);
  const container = {
    id: 'container-id',
    start: vi.fn(async () => {
      if (options.startError) throw options.startError;
    }),
    stop: vi.fn(async () => undefined),
    remove: containerRemove,
    exec: vi.fn(async () => ({ start: vi.fn(async () => undefined), inspect: vi.fn(async () => ({ Running: false, ExitCode: 0 })) })),
    inspect: vi.fn(async () => ({
      State: {
        Running: options.ingressRunning ?? true,
        OOMKilled: options.oomKilled ?? false,
        Health: { Status: 'healthy' },
      },
      Config: {
        Labels: {
          'cyber-range.managed': 'true',
          'cyber-range.instance-id': options.managedInstanceId ?? INSTANCE_ID,
          'cyber-range.challenge-id': options.managedChallengeId ?? CHALLENGE_ID,
          ...(options.entryServices ? { 'cyber-range.services': options.entryServices } : {}),
        },
      },
      NetworkSettings: {
        Networks: {
          [`crn-${INSTANCE_ID.replaceAll('-', '')}`]: { IPAddress: '172.18.0.5' },
          ...(options.extraNetwork ? { bridge: {} } : {}),
        },
      },
    })),
  };
  let ingressAttached = options.ingressAttached ?? false;
  const networkConnect = vi.fn(async () => { ingressAttached = true; });
  const networkDisconnect = vi.fn(async () => { ingressAttached = false; });
  const network = {
    id: 'network-id',
    connect: networkConnect,
    disconnect: networkDisconnect,
    remove: networkRemove,
    inspect: vi.fn(async () => ({
      Name: `crn-${INSTANCE_ID.replaceAll('-', '')}`,
      Driver: options.networkDriver ?? 'bridge',
      EnableIPv6: options.enableIPv6 ?? false,
      Internal: true,
      Attachable: false,
      Options: options.networkOptions ?? {
        'com.docker.network.bridge.gateway_mode_ipv4': 'isolated',
        'com.docker.network.bridge.gateway_mode_ipv6': 'isolated',
      },
      Containers: ingressAttached ? { 'ingress-id': { Name: 'traefik' } } : {},
      Labels: {
        'cyber-range.managed': 'true',
        'cyber-range.instance-id': options.managedInstanceId ?? INSTANCE_ID,
        'cyber-range.challenge-id': options.managedChallengeId ?? CHALLENGE_ID,
      },
    })),
  };
  const createContainer = vi.fn(async (_options: Docker.ContainerCreateOptions) => container);
  const createNetwork = vi.fn(async (_options: Docker.NetworkCreateOptions) => network);
  const getContainer = vi.fn(() => container);
  const getImage = vi.fn((image: string) => ({
    inspect: vi.fn(async () => {
      if (options.availableImages && !options.availableImages.includes(image)) {
        throw { statusCode: 404 };
      }
      return { Id: 'image-id' };
    }),
  }));
  const docker = {
    info: vi.fn(async () => ({
      ServerVersion: options.serverVersion ?? '29.8.1',
      SecurityOptions: options.securityOptions ?? [
        'name=userns',
        'name=seccomp,profile=default',
        'name=apparmor',
      ],
      Runtimes: options.runtimes ?? { runc: { path: 'runc' } },
    })),
    listContainers: vi.fn(async () => options.existingContainer ? [{ Id: 'container-id' }] : []),
    listNetworks: vi.fn(async () => options.existingNetwork ? [{ Id: 'network-id' }] : []),
    createContainer,
    createNetwork,
    getContainer,
    getNetwork: vi.fn(() => network),
    getImage,
  };
  return {
    docker: docker as unknown as Docker,
    createContainer,
    createNetwork,
    getContainer,
    getImage,
    containerRemove,
    networkRemove,
    networkConnect,
    networkDisconnect,
  };
}
